/* ── Filing to the archive, from the five non-JSA workflows ──────────────
   Switched OFF 2026-09-10, deliberately, at Fonzo's call.

   The archive has no edit and no delete — that absence is the whole
   guarantee that a filed record is what actually happened. Which also
   means a document filed half-finished is wrong forever, and half-finished
   is the normal case on the five that need other people: an incident
   report waiting on a witness statement, a medical event waiting on a
   doctor's note.

   Until there is somewhere for a document to live while it is still being
   worked on -- see the "Before It's Filed" scope -- the safe answer is
   that nothing new goes in. Download and print still work exactly as
   before, so no work is lost and nothing is blocked; it just stays on the
   device and on paper for now.

   NOT affected:
     - JSAs, which still file themselves when a published one expires.
       Those are complete by definition: the shift ended and the crew
       signed.
     - Adding an existing document from inside the Archive screen itself.
       That is a deliberate office action on a finished PDF somebody is
       holding, not the end of a half-filled form.

   Flip this to true when open documents ship, and the button becomes
   "file it now that it's finished" rather than a trap at the end of a
   workflow. */

